import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { readPng, writePng } from './png.mjs';

// Prepare the original green-matte seal sheet for every game entry.
// Keep this optional form outside the JS bundle so other players never download it.
const manifest = JSON.parse(await readFile(new URL('../char/manifest.json', import.meta.url), 'utf8'));
const source = await readFile(new URL(`../char/${manifest.player.directory}/${manifest.player.files.sealSpriteSheet}`, import.meta.url));
const decoded = readPng(source);
const pixels = Buffer.alloc(decoded.width * decoded.height * 4);
for (let i = 0; i < decoded.width * decoded.height; i++) {
  const from = i * decoded.bpp, to = i * 4;
  const red = decoded.pixels[from], green = decoded.pixels[from + 1], blue = decoded.pixels[from + 2];
  pixels[to] = red; pixels[to + 1] = green; pixels[to + 2] = blue;
  pixels[to + 3] = green > red + 15 && green > blue + 15 ? 0 : decoded.bpp === 4 ? decoded.pixels[from + 3] : 255;
}
const image = writePng({ width: decoded.width, height: decoded.height, colorType: 6, pixels });
const version = createHash('sha256').update(image).digest('hex').slice(0, 12);
await mkdir(new URL('../img/generated/', import.meta.url), { recursive: true });
await writeFile(new URL('../img/generated/seal-sprite.png', import.meta.url), image);
const outputDirectory = new URL('../js/generated/core/', import.meta.url);
await mkdir(outputDirectory, { recursive: true });
await writeFile(new URL('seal-sprite.generated.ts', outputDirectory),
  '// Generated by scripts/generate-seal-sprite.mjs. Do not edit.\n' +
  `export const SEAL_SPRITE_SOURCE = ${JSON.stringify(`img/generated/seal-sprite.png?v=${version}`)};\n`,
);
