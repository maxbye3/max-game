import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { decodePhotoFeed, encodePhotoFeed, photoKeys } from './lib/protected-photo-feeds.mjs';

// Stable across content refreshes and cached game bundles. These client-side
// keys deter casual inspection; they cannot provide access control on a static site.

await mkdir('js/generated/interiors', { recursive: true });
await mkdir('data/protected', { recursive: true });
for (const name of Object.keys(photoKeys)) {
  const { images } = decodePhotoFeed(name, JSON.parse(await readFile(`scripts/photo-sources/photos-${name}.json`, 'utf8')));
  if (!Array.isArray(images) || !images.every(source => typeof source === 'string' && /^https:\/\/lh3\.googleusercontent\.com\//.test(source))) {
    throw new Error(`Invalid ${name} photo sources`);
  }
  await writeFile(`data/protected/photos-${name}.json`, JSON.stringify(encodePhotoFeed(name, { images })) + '\n');
}
await writeFile('js/generated/interiors/photo-keys.generated.ts', `// Generated by scripts/generate-protected-photos.mjs.\nexport const PHOTO_KEYS = ${JSON.stringify(photoKeys)} as const;\n`);
